      public void cargarAreasEnCombo() {
        cboArea.removeAllItems();
        String ruta = "src/Datos/areas.csv";
        try (BufferedReader br = new BufferedReader(new FileReader(ruta))) {
            String linea;
            boolean primera = true;
            while ((linea = br.readLine()) != null) {
                if (primera) {
                    primera = false; // Saltar encabezados
                    continue;
                }
                if (linea.trim().isEmpty()) continue;
                // codigo,nombre,ubicacion
                String[] col = linea.split(",");
                if (col.length >= 2) {
                    cboArea.addItem(col[1].trim()); // Agrega el nombre del área
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar áreas al combo: " + e.getMessage());
        }
    }
      
         public void listarCampañas() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Código");
        modelo.addColumn("Nombre Campaña");
        modelo.addColumn("Área");
        modelo.addColumn("Fecha Inicio");
        modelo.addColumn("Fecha Fin");
        modelo.addColumn("Presupuesto");
        String ruta = "src/Datos/campañas.csv";
        try (BufferedReader br = new BufferedReader(new FileReader(ruta))) {
            String linea;
            boolean primera = true;
            while ((linea = br.readLine()) != null) {
                if (primera) {
                    primera = false; // Saltar encabezados
                    continue;
                }
                if (linea.trim().isEmpty()) continue;
                // codigo,nombre,area,fechaInicio,fechaFin,presupuesto
                String[] col = linea.split(",");
                if (col.length >= 6) {
                    modelo.addRow(col);
                }
            }
            tblCampañas.setModel(modelo);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al listar campañas: " + e.getMessage());
        }
    }


