    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
          String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String area = cboArea.getSelectedItem() != null ? cboArea.getSelectedItem().toString() : "";
        String fIni = txtFechaInicio.getText().trim();
        String fFin = txtFechaFin.getText().trim();
        String pres = txtPresupuesto.getText().trim();
        if (codigo.isEmpty() || nombre.isEmpty() || area.isEmpty() || fIni.isEmpty() || pres.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos obligatorios.");
            return;
        }
        // 1. Instanciamos la clase del Modelo usando POO
        double presupuestoNum = 0.0;
        try {
            presupuestoNum = Double.parseDouble(pres);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El presupuesto debe ser un número válido.");
            return;
        }

        Modelo.CampañaExploracion nuevaCamp = new Modelo.CampañaExploracion(codigo, nombre, area, fIni, fFin, presupuestoNum);

        // 2. Formato para campañas.csv usando los getters del objeto instanciado
        String linea = nuevaCamp.getCodigo() + "," + nuevaCamp.getNombre() + "," + nuevaCamp.getArea() + "," + nuevaCamp.getFechaInicio() + "," + nuevaCamp.getFechaFin() + "," + nuevaCamp.getPresupuesto();
        String ruta = "src/Datos/campañas.csv";
        try (PrintWriter pw = new PrintWriter(new FileWriter(ruta, true))) {
            pw.println(linea);
            pw.flush();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar campaña: " + e.getMessage());
            return;
        }

        JOptionPane.showMessageDialog(this, "Campaña registrada exitosamente.");

        // Limpiar cajas
        txtCodigo.setText("");
        txtNombre.setText("");
        txtFechaInicio.setText("");
        txtFechaFin.setText("");
        txtPresupuesto.setText("");

        // Recargar la tabla inmediatamente
        listarCampañas();
    }//GEN-LAST:event_jButton1ActionPerformed

