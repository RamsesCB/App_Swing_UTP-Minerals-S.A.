    public String iniciarSession(String usuario, String clave) {
        String rutaCsv = "src/Datos/usuarios.csv";

        try (BufferedReader br = new BufferedReader(new FileReader(rutaCsv))) {
            String linea;
            boolean primeraLinea = true;

            while ((linea = br.readLine()) != null) {
                if (primeraLinea) {
                    primeraLinea = false; // Saltar encabezados
                    continue;
                }
                if (linea.trim().isEmpty()) {
                    continue;
                }

                String[] columnas = linea.split(",");
                String userCsv = columnas[0].trim();
                String passCsv = columnas[1].trim();
                String rolCsv = columnas[2].trim();

                if (userCsv.equalsIgnoreCase(usuario) && passCsv.equals(clave)) {
                    return rolCsv; // Retorna: GERENTE, GEOLOGO, TOPOGRAFO o TECNICO_CAMPO
                }
            }
        } catch (java.io.IOException e) {
         JOptionPane.showMessageDialog(this, "Error al leer usuarios: " + e.getMessage());
        }

        return null;
    }
    
    
