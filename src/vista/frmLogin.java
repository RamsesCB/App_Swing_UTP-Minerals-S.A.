    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String usuario = txtUsuario.getText().trim();
        String clave = txtContraseña.getText().trim();

        if (usuario.isEmpty() || clave.isEmpty()) {
           JOptionPane.showMessageDialog(this, "Por favor, ingrese usuario y contraseña.");
            return;
        }

        String rol = iniciarSession(usuario, clave);

        if (rol != null) {
            JOptionPane.showMessageDialog(this, "¡Bienvenido! Rol: " + rol);
            frmPrincipal principal = new frmPrincipal();
            principal.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, 
                "Usuario o contraseña incorrectos.", "Error de Login", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

