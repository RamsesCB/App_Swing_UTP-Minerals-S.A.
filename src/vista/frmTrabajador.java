    private void btnAgregarTrabajadorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTrabajadorActionPerformed
          String rol = cbEspecilidad.getSelectedItem().toString();
        String tipoDocTexto = cbTipoDocumento.getSelectedItem().toString();
        String numDocStr = txtNumDocumento.getText().trim();
        String nombres = txtNombres.getText().trim();
        String apePaterno = txtAPaterno.getText().trim();
        String apeMaterno = txtAMaterno.getText().trim();
        if (numDocStr.isEmpty() || nombres.isEmpty() || apePaterno.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete los campos obligatorios.");
            return;
        }
        int numDocumento = Integer.parseInt(numDocStr);
        // 1. Instanciamos TipoDoc (tu clase del Modelo)
        Modelo.TipoDoc tipoDoc = new Modelo.TipoDoc(tipoDocTexto);
        // 2. APLICAMOS POLIMORFISMO con la clase abstracta Trabajador:
        Modelo.Trabajador nuevoTrabajador = null;
        if (rol.equalsIgnoreCase("GEOLOGO")) {
            nuevoTrabajador = new Geologo(nombres, apePaterno, apeMaterno, tipoDoc, numDocumento);
        } else if (rol.equalsIgnoreCase("TOPOGRAFO")) {
            nuevoTrabajador = new Modelo.Topografo(nombres, apePaterno, apeMaterno, tipoDoc, numDocumento);
        } else if (rol.equalsIgnoreCase("TECNICO_CAMPO")) {
            nuevoTrabajador = new TecnicoCampo(nombres, apePaterno, apeMaterno, tipoDoc, numDocumento);
        }
        // 3. Escribimos al CSV de trabajadores
        String linea = rol + "," + tipoDoc.getNombre() + "," + numDocumento + "," + nombres + "," + apePaterno + "," + apeMaterno;
        String ruta = "src/Datos/trabajadores.csv";
        try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(ruta, true))) {
            pw.println(linea);
            pw.flush();
        } catch (java.io.IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this, "Trabajador registrado exitosamente.");

        // Limpiar campos y recargar
        txtNumDocumento.setText("");
        txtNombres.setText("");
        txtAPaterno.setText("");
        txtAMaterno.setText("");
        listarTrabajadores();
    }//GEN-LAST:event_btnAgregarTrabajadorActionPerformed

