  public void listarTrabajadores() {
        // 1. Crear el modelo con las 5 cabeceras correctas
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Cargo / Rol");
        modelo.addColumn("Tipo Doc");
        modelo.addColumn("N° Documento");
        modelo.addColumn("Nombres");
        modelo.addColumn("Apellidos");

        String ruta = "src/Datos/trabajadores.csv";
        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            boolean primera = true;
            while ((linea = br.readLine()) != null) {
                if (primera) {
                    primera = false; // Saltar encabezado
                    continue;
                }
                if (linea.trim().isEmpty()) continue;

                // Formato: rol,tipoDocumento,numDocumento,nombre,apellidoPaterno,apellidoMaterno
                String[] col = linea.split(",");
                if (col.length >= 6) {
                    String rol = col[0].trim();
                    String tipoDoc = col[1].trim();
                    String numDoc = col[2].trim();
                    String nombres = col[3].trim();
                    String apellidos = col[4].trim() + " " + col[5].trim();

                    modelo.addRow(new Object[]{rol, tipoDoc, numDoc, nombres, apellidos});
                }
            }
            // Asignar a la tabla
            tblTrabajador.setModel(modelo);
        } catch (java.io.IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar trabajadores: " + e.getMessage());
        }
    }

